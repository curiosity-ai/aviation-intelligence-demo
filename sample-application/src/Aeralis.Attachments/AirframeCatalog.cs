using Aeralis.Dataset;
using Aeralis.Dataset.Reference;
using Aeralis.Illustrations;

namespace Aeralis.Attachments;

/// <summary>Where on the airframe something is, and which view shows it.</summary>
/// <param name="Section">The part of the airframe to point at.</param>
/// <param name="View">The view the feature is visible and distinguishable on.</param>
/// <param name="Position">How far along the section, 0 forward/inboard to 1 aft/outboard.</param>
/// <param name="Label">What to call it on the drawing.</param>
public readonly record struct Placement(AircraftSection Section, ViewKind View, double Position, string Label);

/// <summary>
/// Resolves a zone or an ATA chapter to a place on the airframe.
/// </summary>
/// <remarks>
/// The placement is data, not code: <c>zones.csv</c> carries <c>airframe_section</c>,
/// <c>view_hint</c> and <c>section_position</c> per zone, and <c>ata_chapters.csv</c> carries
/// the first two per chapter as the fallback for a document that lists no zone — every FCOM
/// entry, and a handful of others. Both are generated by <c>tools/gen_reference.py</c> and
/// <c>tools/ata_catalog.py</c> from the row's own name, so they are stable.
/// </remarks>
public sealed class AirframeCatalog
{
    private readonly Dictionary<string, ZoneRow> _zones;
    private readonly Dictionary<string, AtaChapter> _ata;

    public AirframeCatalog(ReferenceData reference)
    {
        ArgumentNullException.ThrowIfNull(reference);
        _zones = reference.Zones
            .GroupBy(z => z.Zone, StringComparer.Ordinal)
            .ToDictionary(g => g.Key, g => g.First(), StringComparer.Ordinal);
        _ata = reference.AtaChapters
            .GroupBy(a => a.Code, StringComparer.Ordinal)
            .ToDictionary(g => g.Key, g => g.First(), StringComparer.Ordinal);
    }

    /// <summary>The placement of a zone, or null if the zone is unknown or unplaced.</summary>
    public Placement? ForZone(string? zone)
    {
        if (zone is null || !_zones.TryGetValue(zone, out var row)) return null;
        if (!TryParse(row.AirframeSection, row.ViewHint, out var section, out var view)) return null;

        return new Placement(section, view, Clamp(row.SectionPosition), ZoneLabel(row));
    }

    /// <summary>
    /// The placement of an ATA chapter, tried at 6D then 4D then 2D. The position is the
    /// middle of the section: a chapter names a system, not a station along the airframe.
    /// </summary>
    public Placement? ForAta(params string?[] codes)
    {
        foreach (var code in codes)
        {
            if (code is null || !_ata.TryGetValue(code, out var row)) continue;
            if (!TryParse(row.AirframeSection, row.ViewHint, out var section, out var view)) continue;

            return new Placement(section, view, 0.5, row.Title);
        }
        return null;
    }

    /// <summary>The zone's own name, without the detail suffix the generator appends.</summary>
    /// <remarks>
    /// A zone reads "Fwd Cargo Compartment, LH — Fwd Section". On a drawing the label has to
    /// fit beside the aircraft, and the part before the dash is the part that identifies it.
    /// </remarks>
    private static string ZoneLabel(ZoneRow row)
    {
        var name = row.ZoneName;
        var dash = name.IndexOf('—');
        var head = dash > 0 ? name[..dash].Trim() : name.Trim();
        return $"Zone {row.Zone}\n{head}";
    }

    private static bool TryParse(string sectionName, string viewName,
        out AircraftSection section, out ViewKind view)
    {
        view = default;
        return Enum.TryParse(sectionName, out section) && Enum.TryParse(viewName, out view);
    }

    private static double Clamp(double position) => Math.Clamp(position, 0.05, 0.95);
}
