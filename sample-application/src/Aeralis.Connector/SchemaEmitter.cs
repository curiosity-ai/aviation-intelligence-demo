using System.Reflection;
using System.Text;
using Curiosity.Library;

namespace Aeralis.Connector;

/// <summary>
/// Writes the front-end's <c>Schema/N.cs</c> from the connector's own <c>[Node]</c> classes.
///
/// The workspace generates exactly this file for a front-end project — one nested class per
/// node type, a <c>Type</c> constant plus one constant per field, and a flat <c>E</c> of edge
/// names (<c>WebsiteController.CreateSchemaHelperForFrontEnd</c>, and the server-side twin in
/// <c>CodeManager.AppendNodeSchemasHelperClass</c> that endpoint scripts get injected). But
/// the workspace can only generate it from a graph that has already been ingested, and it is
/// this connector that decides what that graph contains.
///
/// So it is generated here instead, from the same classes <c>SyncSchemaAsync</c> registers.
/// Both sides then spell every node type and every field the same way, and a renamed property
/// breaks the front-end build rather than turning into a silently-empty label at run time.
///
///     dotnet run --project src/Aeralis.Connector -- --emit-frontend-schema \
///         src/Aeralis.FrontEnd/src/Schema/N.cs
/// </summary>
internal static class SchemaEmitter
{
    /// <summary>
    /// Node types the graph owns rather than this connector, with the fields the front-end
    /// reads off them. They cannot be reflected over — there is no <c>[Node]</c> class for
    /// them here — so they are listed, taken from the types' own <c>WriteAsJson</c>.
    /// </summary>
    private static readonly (string Type, string[] Fields)[] GraphOwnedTypes =
    [
        ("_User", ["UserName", "FullName", "FirstName", "LastName", "Email", "Active"]),
        ("_FileEntry", ["OriginalName", "ContentType", "Indexed", "PagesCount", "ThumbnailsCount", "Size"]),
    ];

    /// <summary>
    /// Edges the workspace writes, not this connector: the NLP layer, and the attachment
    /// edges already named in <see cref="Edges"/>.
    /// </summary>
    private static readonly string[] GraphOwnedEdges = ["_AppearsIn", "_Mentions"];

    public static void Emit(string path)
    {
        var nodeTypes = typeof(SchemaEmitter).Assembly
            .GetTypes()
            .Where(t => t.GetCustomAttribute<NodeAttribute>() is object)
            .OrderBy(t => t.Name, StringComparer.OrdinalIgnoreCase)
            .ToList();

        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("//     Generated from the connector's [Node] schema classes by");
        sb.AppendLine("//     src/Aeralis.Connector/SchemaEmitter.cs. Do not edit by hand:");
        sb.AppendLine("//");
        sb.AppendLine("//         dotnet run --project src/Aeralis.Connector -- \\");
        sb.AppendLine("//             --emit-frontend-schema src/Aeralis.FrontEnd/src/Schema/N.cs");
        sb.AppendLine("//");
        sb.AppendLine("//     This is the same shape the workspace generates for a front-end project");
        sb.AppendLine("//     (WebsiteController.CreateSchemaHelperForFrontEnd) and the same shape the");
        sb.AppendLine("//     endpoint scripts are compiled against, so `N.Modification.DocId` means the");
        sb.AppendLine("//     same thing in the front-end, in an endpoint and in the connector.");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine();
        sb.AppendLine("namespace Aeralis.FrontEnd.Schema");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>Node types and their field names, as the connector writes them.</summary>");
        sb.AppendLine("    internal static class N");
        sb.AppendLine("    {");

        foreach (var type in nodeTypes)
        {
            AppendNodeType(sb, type.Name, FieldsOf(type));
        }

        foreach (var (typeName, fields) in GraphOwnedTypes)
        {
            AppendNodeType(sb, typeName, fields);
        }

        AppendTypeGroups(sb, nodeTypes);

        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>Edge names, as the connector writes them.</summary>");
        sb.AppendLine("    internal static class E");
        sb.AppendLine("    {");

        var edges = typeof(Edges)
            .GetFields(BindingFlags.Public | BindingFlags.Static)
            .Where(f => f.IsLiteral && f.FieldType == typeof(string))
            .Select(f => (Name: f.Name, Value: (string)f.GetRawConstantValue()!))
            .OrderBy(e => e.Name, StringComparer.OrdinalIgnoreCase);

        foreach (var (name, value) in edges)
        {
            // An edge whose name differs from its identifier is one the graph owns
            // (`_HasAttachment`), so it is spelled out rather than written as nameof.
            sb.Append("        public const string ").Append(name).Append(" = ")
              .Append(name == value ? "nameof(" + name + ")" : "\"" + value + "\"")
              .AppendLine(";");
        }

        foreach (var edge in GraphOwnedEdges)
        {
            sb.Append("        public const string ").Append(edge.TrimStart('_'))
              .Append(" = \"").Append(edge).AppendLine("\";");
        }

        sb.AppendLine("    }");
        sb.AppendLine("}");

        Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(path))!);
        File.WriteAllText(path, sb.ToString().ReplaceLineEndings("\n"));

        Console.WriteLine($"wrote {path}: {nodeTypes.Count + GraphOwnedTypes.Length} node types");
    }

    private static void AppendNodeType(StringBuilder sb, string typeName, IEnumerable<string> fields)
    {
        sb.Append("        public sealed class ").AppendLine(typeName);
        sb.AppendLine("        {");
        sb.Append("            public const string Type = \"").Append(typeName).AppendLine("\";");

        foreach (var field in fields)
        {
            // A field named after its own type would shadow the class; the workspace's
            // generator suffixes it and keeps the value, so this does too.
            var identifier = field == typeName ? field + "_" : field;
            sb.Append("            public const string ").Append(identifier)
              .Append(" = \"").Append(field).AppendLine("\";");
        }

        sb.AppendLine("        }");
        sb.AppendLine();
    }

    /// <summary>
    /// The two type lists the 360 views are built from. They are derived from the schema
    /// rather than listed, so a new document type joins them by existing.
    /// </summary>
    private static void AppendTypeGroups(StringBuilder sb, IReadOnlyList<Type> nodeTypes)
    {
        var documents = nodeTypes
            .Where(t => t.DeclaringType == typeof(Ingest.DocumentSchema) && !IsChildNode(t.Name))
            .Select(t => t.Name)
            .ToList();

        // Everything except the issue snapshots and the rendered-source nodes, which are
        // history rather than neighbourhood and would swamp a 360 view.
        var all360 = nodeTypes
            .Select(t => t.Name)
            .Where(name => !name.EndsWith("Issue", StringComparison.Ordinal)
                           && name != nameof(Ingest.AttachmentsIngest.DocumentationSource))
            .ToList();

        sb.AppendLine("        /// <summary>Every document type — the default breadth of a 360 view.</summary>");
        sb.AppendLine("        public static readonly string[] DocumentTypes =");
        AppendTypeArray(sb, documents);

        sb.AppendLine("        /// <summary>Documents plus the reference and child types worth surfacing beside them.</summary>");
        sb.AppendLine("        public static readonly string[] All360Types =");
        AppendTypeArray(sb, all360);
    }

    private static bool IsChildNode(string name) =>
        name is "IpcItem" or "RepairDrawing" or "ExpectedFinding" or "SbRevision" or "MsnRangeApplicability";

    private static void AppendTypeArray(StringBuilder sb, IReadOnlyList<string> names)
    {
        sb.AppendLine("        {");
        foreach (var name in names) sb.Append("            ").Append(name).AppendLine(".Type,");
        sb.AppendLine("        };");
        sb.AppendLine();
    }

    private static IEnumerable<string> FieldsOf(Type type)
    {
        // Key first, then the rest in declaration order — the same ordering the workspace's
        // own generator uses, so the two files diff cleanly against each other.
        var properties = type.GetProperties(BindingFlags.Public | BindingFlags.Instance)
            .Where(p => p.GetCustomAttribute<KeyAttribute>() is object
                        || p.GetCustomAttribute<PropertyAttribute>() is object
                        || p.GetCustomAttribute<TimestampAttribute>() is object)
            .ToList();

        return properties
            .OrderBy(p => p.GetCustomAttribute<KeyAttribute>() is object ? 0 : 1)
            .Select(p => p.Name);
    }
}
